/**
 * Root Layout Component
 *
 * This is the main layout component that wraps all pages in the application.
 * It provides essential context providers and styling configurations.
 */

import type { Metadata } from "next";
import { Geist, Geist_Mono } from "next/font/google";
import "./globals.css";
import { CsrfProvider } from "@/context/CsrfContext";
import { UserProvider } from "@/context/UserContext";
import LayoutWrapper from "@/components/LayoutWrapper";

// Configure Geist Sans font for the application
const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

// Configure Geist Mono font for monospace text
const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

// Application metadata configuration
export const metadata: Metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
};

/**
 * RootLayout Component
 *
 * @param {Object} props - Component props
 * @param {React.ReactNode} props.children - Child components to be rendered
 *
 * This component:
 * 1. Sets up the HTML structure with proper language attribute
 * 2. Applies font configurations
 * 3. Wraps the application with necessary context providers:
 *    - UserProvider: Manages user authentication state
 *    - CsrfProvider: Handles CSRF token management
 * 4. Applies the LayoutWrapper component for consistent layout structure
 */
export default function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  return (
    <html lang="en">
      <body
        className={`${geistSans.variable} ${geistMono.variable} antialiased`}
      >
        <UserProvider>
          <CsrfProvider>
            <LayoutWrapper>{children}</LayoutWrapper>
          </CsrfProvider>
        </UserProvider>
      </body>
    </html>
  );
}
